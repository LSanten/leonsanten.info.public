#!/usr/bin/env python3
"""Forward old marble pages on leonsanten.info to their new home on leons.bloob.haus.

The mapping lives in python/marble_redirects.csv (next to this script), with the
columns old_path,new_url,status,note:

  old_path  page inside docs/, e.g. marbles/THESIS-HOLISTIC-ENGINEERING/index.html
  new_url   where that page lives now, e.g. https://leons.bloob.haus/marbles/THESIS-HOLISTIC-ENGINEERING/
  status    redirect  -> this script turns old_path into a small redirect page
            unsure    -> left alone (several possible targets, or the name changed a lot)
            no_match  -> left alone (no public page on Bloob Haus)
  note      free text for humans

Only rows with status "redirect" are touched. Everything else in the marble
folders (images, media, other files) is never changed.

To rewire a marble later: edit its new_url (or set status to redirect) in the CSV
and run this script again. It is idempotent: it keeps the original <title>, also
when the page is already a redirect page, so running it twice changes nothing.

Usage (from the docs/ folder):
  python3 python/make_marble_redirects.py             write or update redirect pages
  python3 python/make_marble_redirects.py --dry-run   only report what would change
  python3 python/make_marble_redirects.py --verify    first check that every new_url
                                                      returns HTTP 200, skip rows that fail

To undo the redirects, revert the git commit that added them.
"""

import argparse
import csv
import html
import json
import os
import re
import sys
import urllib.request

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SITE_ROOT = os.path.dirname(SCRIPT_DIR)  # the docs/ folder
CSV_PATH = os.path.join(SCRIPT_DIR, "marble_redirects.csv")
MARKER = "<!-- marble-redirect: generated by python/make_marble_redirects.py from python/marble_redirects.csv -->"

TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
{marker}
<meta charset="utf-8">
<title>{title}</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="refresh" content="0; url={url_attr}">
<link rel="canonical" href="{url_attr}">
<script>location.replace({url_js} + location.hash);</script>
</head>
<body>
<p>This page moved to <a href="{url_attr}">{url_text}</a></p>
</body>
</html>
"""

TITLE_RE = re.compile(r"<title[^>]*>(.*?)</title>", re.IGNORECASE | re.DOTALL)


def read_title(path, fallback):
    """Return the inner text of the page's <title>, as written in the HTML."""
    with open(path, encoding="utf-8", errors="surrogateescape") as f:
        text = f.read()
    match = TITLE_RE.search(text)
    if not match or not match.group(1).strip():
        return fallback
    return match.group(1).strip()


def url_ok(url):
    request = urllib.request.Request(url, headers={"User-Agent": "marble-redirect-check"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.status == 200
    except Exception:
        return False


def safe_target(old_path):
    """Resolve old_path inside docs/marbles/ and refuse anything else."""
    if not old_path.endswith("index.html"):
        return None
    full = os.path.normpath(os.path.join(SITE_ROOT, old_path))
    marbles_dir = os.path.join(SITE_ROOT, "marbles") + os.sep
    if not full.startswith(marbles_dir):
        return None
    return full


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="report changes without writing files")
    parser.add_argument("--verify", action="store_true", help="skip rows whose new_url does not return HTTP 200")
    args = parser.parse_args()

    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    counts = {"written": 0, "unchanged": 0, "skipped": 0, "left alone": 0}
    for row in rows:
        old_path = row["old_path"].strip()
        new_url = row["new_url"].strip()
        status = row["status"].strip()

        if status != "redirect":
            counts["left alone"] += 1
            continue
        if not new_url.startswith("https://"):
            print(f"SKIP (new_url must start with https://): {old_path}")
            counts["skipped"] += 1
            continue
        target = safe_target(old_path)
        if target is None:
            print(f"SKIP (old_path must be a marbles/.../index.html page): {old_path}")
            counts["skipped"] += 1
            continue
        if not os.path.isfile(target):
            # Never create new pages, only replace existing ones.
            print(f"SKIP (file not found): {old_path}")
            counts["skipped"] += 1
            continue
        if args.verify and not url_ok(new_url):
            print(f"SKIP (new_url does not return 200): {old_path} -> {new_url}")
            counts["skipped"] += 1
            continue

        folder_name = os.path.basename(os.path.dirname(target))
        title = read_title(target, fallback=html.escape(folder_name))
        page = TEMPLATE.format(
            marker=MARKER,
            title=title,
            url_attr=html.escape(new_url, quote=True),
            url_text=html.escape(new_url),
            url_js=json.dumps(new_url),
        )

        with open(target, encoding="utf-8", errors="surrogateescape") as f:
            current = f.read()
        if current == page:
            counts["unchanged"] += 1
            continue
        if not args.dry_run:
            with open(target, "w", encoding="utf-8", errors="surrogateescape", newline="\n") as f:
                f.write(page)
        print(f"{'WOULD WRITE' if args.dry_run else 'WROTE'}: {old_path} -> {new_url}")
        counts["written"] += 1

    summary = ", ".join(f"{key}: {value}" for key, value in counts.items())
    print(f"Done{' (dry run)' if args.dry_run else ''}. {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
